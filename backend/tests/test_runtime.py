@needs_engine
@pytest.mark.skipif(not sys.platform.startswith("linux"), reason="Linux parent-death signal")
def test_engine_dies_if_backend_is_killed(tmp_path):
    """If the backend is killed outright (no clean shutdown), the engine must not linger."""
    import signal
    import subprocess
    import textwrap
    import time

    tiny = write_tiny(tmp_path / "tiny-Q4_K_M.gguf")
    script = tmp_path / "host.py"
    script.write_text(textwrap.dedent(f"""
        import asyncio, sys
        from pathlib import Path
        from claw.runtime.engine import LlamaServer
        async def main():
            e = LlamaServer()
            await e.ensure("t", Path({str(tiny)!r}))
            print(e._proc.pid, flush=True)
            await asyncio.sleep(60)
        asyncio.run(main())
    """))
    backend = str(Path(__file__).resolve().parents[1])
    host = subprocess.Popen([sys.executable, str(script)], stdout=subprocess.PIPE, cwd=backend, env={**os.environ, "PYTHONPATH": backend})
    engine_pid = int(host.stdout.readline())
    assert os.path.exists(f"/proc/{engine_pid}")
    host.send_signal(signal.SIGKILL)
    host.wait()
    for _ in range(50):
        if not os.path.exists(f"/proc/{engine_pid}") or "Z" in open(f"/proc/{engine_pid}/stat").read().split()[2]:
            break
        time.sleep(0.1)
    alive = os.path.exists(f"/proc/{engine_pid}") and "Z" not in open(f"/proc/{engine_pid}/stat").read().split()[2]
    assert not alive, "engine outlived a killed backend"
