async def test_download_verifies_checksum(lib, tmp_path, tiny):
    f = hub.RemoteFile("Qwen3VL-4B-Instruct-Q4_K_M.gguf", tiny.stat().st_size, None)
    r = await hub.resolve(catalog.get("qwen3-vl-4b"))
    seen = []
    ok = await hub.download_file(r.repo, r.model, tmp_path / r.model.name, lambda d, t: seen.append(d), asyncio.Event())
    assert ok and (tmp_path / r.model.name).read_bytes() == tiny.read_bytes() and seen[-1] == r.model.size
    lib.repos[r.repo]["sha_override"] = {r.model.name: "0" * 64}
    bad = await hub.resolve(catalog.get("qwen3-vl-4b"))
    with pytest.raises(hub.DownloadError, match="integrity check"):
        await hub.download_file(bad.repo, bad.model, tmp_path / "again.gguf", lambda *a: None, asyncio.Event())
    assert not (tmp_path / "again.gguf").exists() and not (tmp_path / "again.gguf.part").exists()
    del f


