def test_app_with_builtin_brain_and_no_ollama(tmp_path, tiny, lib, no_ollama, monkeypatch):
    monkeypatch.setattr(engine_mod, "detect", lambda: hw(ram=8))
    from claw.runtime import brain as brain_mod

    monkeypatch.setattr(brain_mod, "detect", lambda: hw(ram=8))
    with TestClient(create_app(tmp_path / "data", TOKEN), base_url="http://127.0.0.1") as c:
        c.headers["X-Claw-Token"] = TOKEN
        b = c.get("/brain").json()
        assert b["mode"] == "builtin" and not b["ready"] and b["recommended"] == "qwen3-vl-4b"
        r = c.post("/tasks/plan", json={"task": "Plan something useful"})
        assert r.status_code == 502 and "doesn't have a brain" in r.json()["error"]["message"]
        assert c.post("/brain/download", json={"id": "qwen3-vl-4b"}).status_code == 200
        for _ in range(200):
            b = c.get("/brain").json()
            if b["download"]["status"] in ("done", "failed"):
                break
            time.sleep(0.05)
        assert b["ready"] and b["active"]["id"] == "qwen3-vl-4b"
        # The stand-in library's vision file is fake, so the real engine refuses it: Claw must say so clearly.
        r = c.post("/tasks/plan", json={"task": "Plan something useful"})
        assert r.status_code == 502 and "could not be loaded" in r.json()["error"]["message"]
        assert c.get("/brain").json()["engine"]["state"] == "failed"
        assert c.post("/brain/select", json={"id": "nope"}).status_code == 404
        # A real (tiny) model chosen from this computer: the engine starts on demand and answers.
        imp = c.post("/brain/import", json={"path": str(tiny)})
        assert imp.status_code == 200 and imp.json()["active"]["kind"] == "imported"
        r = c.post("/tasks/plan", json={"task": "Plan something useful"})
        assert r.status_code in (200, 422), r.text  # 422 = random tiny model couldn't make a usable plan; never a crash
        assert c.get("/brain").json()["engine"]["state"] == "ready"
        assert c.post("/brain/restart").status_code == 200
        assert c.get("/brain").json()["engine"]["state"] == "ready"
    assert not any(":11434" in q for q in lib.requests)


