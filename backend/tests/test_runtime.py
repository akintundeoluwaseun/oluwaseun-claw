# ---------- engine ----------
@needs_engine
async def test_engine_start_json_auth_stop(tiny, no_ollama, monkeypatch):
    monkeypatch.setattr(engine_mod, "detect", lambda: hw())
    eng = LlamaServer()
    await eng.ensure("tiny", tiny)
    assert eng.status.state == "ready" and eng.running()
    from claw.models.openai_compat import OpenAICompatAdapter

    a = OpenAICompatAdapter(eng.base_url, "tiny", timeout_s=60, temperature=0)
    a.api_key = eng.api_key
    out = json.loads(await a.chat([ChatMessage(role="user", content="hi")], json_schema=OK_SCHEMA))
    assert isinstance(out["ok"], bool)
    a.api_key = "wrong"
    with pytest.raises(Exception):
        await a.chat([ChatMessage(role="user", content="hi")])
    await eng.ensure("tiny", tiny)  # already running: no restart
    assert eng.status.restarts == 0
    await eng.stop()
    assert eng.status.state == "stopped" and not eng.running()


@needs_engine
async def test_engine_restarts_after_crash(tiny, monkeypatch):
    monkeypatch.setattr(engine_mod, "detect", lambda: hw())
    eng = LlamaServer()
    await eng.ensure("tiny", tiny)
    eng._proc.kill()  # SIGKILL on POSIX, TerminateProcess on Windows (there is no SIGKILL there)
    eng._proc.wait()
    assert await eng.check_alive() is True
    assert eng.status.state == "ready" and eng.status.restarts == 1
    await eng.stop()


