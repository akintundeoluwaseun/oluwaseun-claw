"""A dimensioned part, made in real CAD and measured afterwards (challenge section 12).

Most of section 12 is MATLAB, Simulink, Minitab, AnyLogic and Microsoft
Project - paid software S-CLAW cannot run and does not pretend to. OpenSCAD is
free, scriptable, headless and on every platform, which makes it the one CAD
package that can be both driven and PROVED on any machine, including this one.

The script is generated from numbers, never from text the brain wrote, so a
request cannot inject OpenSCAD code. And the part is checked by measuring the
STL that came out - if the brain asked for 60 x 40 x 8 and the file is not
that size, the tool says so instead of reporting success.
"""

from __future__ import annotations

import asyncio
from pathlib import Path

from pydantic import Field, field_validator

from claw.agent.schemas import Capability
from claw.integrations import openscad as scad
from claw.permissions.policy import RiskLevel
from claw.tools.base import ToolArgs, ToolContext, ToolError, ToolRegistry, ToolResult, ToolSpec
from claw.tools.file_tools import existing_folder, safe_file_name, unique_path

SHAPES = ("plate", "box", "cylinder", "tube", "bracket")
#: Anything bigger is a mistake in millimetres, not a part.
MAX_MM = 2000.0


class PartArgs(ToolArgs):
    shape: str = Field(default="plate", description="plate, box, cylinder, tube or bracket")
    width: float = Field(default=60, gt=0, le=MAX_MM, description="X in millimetres")
    depth: float = Field(default=40, gt=0, le=MAX_MM, description="Y in millimetres")
    height: float = Field(default=8, gt=0, le=MAX_MM, description="Z (thickness) in millimetres")
    diameter: float = Field(default=0, ge=0, le=MAX_MM, description="For cylinder and tube")
    bore: float = Field(default=0, ge=0, le=MAX_MM, description="Inner diameter of a tube")
    hole_diameter: float = Field(default=0, ge=0, le=MAX_MM, description="Corner holes, 0 for none")
    hole_inset: float = Field(default=10, ge=0, le=MAX_MM, description="Hole centre from each edge")
    file_name: str | None = Field(default=None, max_length=100)
    folder: str | None = Field(default=None, max_length=500)

    @field_validator("shape")
    @classmethod
    def _known(cls, v):
        s = (v or "plate").strip().lower()
        if s not in SHAPES:
            raise ValueError(f"shape must be one of: {', '.join(SHAPES)}")
        return s


def script_for(a: PartArgs) -> str:
    """OpenSCAD source built from numbers only."""
    w, d, h = float(a.width), float(a.depth), float(a.height)
    dia = float(a.diameter) or min(w, d)
    body = {
        "plate": f"cube([{w}, {d}, {h}]);",
        "box": f"cube([{w}, {d}, {h}]);",
        "cylinder": f"cylinder(h={h}, d={dia}, $fn=96);",
        "tube": f"difference() {{ cylinder(h={h}, d={dia}, $fn=96); "
                f"translate([0,0,-1]) cylinder(h={h + 2}, d={float(a.bore) or dia / 2}, $fn=96); }}",
        # An L-bracket: a base plate with an upstand along one edge.
        "bracket": f"union() {{ cube([{w}, {d}, {h}]); cube([{h}, {d}, {min(w, d)}]); }}",
    }[a.shape]

    holes = ""
    if a.hole_diameter and a.shape in ("plate", "box", "bracket"):
        r, inset = float(a.hole_diameter) / 2, float(a.hole_inset)
        if inset * 2 + float(a.hole_diameter) > min(w, d):
            raise ToolError(
                f"A {a.hole_diameter} mm hole {inset} mm from each edge does not fit a "
                f"{w} x {d} mm part. Use a smaller hole or a smaller inset.")
        spots = [(inset, inset), (w - inset, inset), (inset, d - inset), (w - inset, d - inset)]
        holes = "".join(
            f"\n    translate([{x}, {y}, -1]) cylinder(h={h + 2}, r={r}, $fn=64);" for x, y in spots)
    return (f"// Generated by S-CLAW from numbers only.\n"
            + (f"difference() {{\n    {body}{holes}\n}}\n" if holes else f"{body}\n"))


def check_part(args: PartArgs, ctx: ToolContext) -> None:
    if not scad.binary():
        raise ToolError("Making a CAD part needs OpenSCAD, which is not installed. "
                        "Install it from openscad.org, then try again.")
    existing_folder(ctx, args.folder)


async def make_part(args: PartArgs, ctx: ToolContext) -> ToolResult:
    """Make a dimensioned part in OpenSCAD and measure the STL it produced."""
    folder = existing_folder(ctx, args.folder)
    out = unique_path(folder / safe_file_name(args.file_name or f"{args.shape}", ".stl"))
    ctx.policy.check_path(out, write=True)
    source = script_for(args)
    try:
        await asyncio.to_thread(scad.render, source, out, 180)
    except RuntimeError as exc:
        raise ToolError(f"OpenSCAD could not make it: {exc}") from exc

    size = await asyncio.to_thread(scad.bounding_box, out)
    if size is None:
        raise ToolError("OpenSCAD wrote a file with no geometry in it.")

    # What it should measure. A cylinder's footprint is its diameter; a bracket
    # stands as tall as its upstand.
    dia = float(args.diameter) or min(args.width, args.depth)
    want = {
        "plate": (args.width, args.depth, args.height),
        "box": (args.width, args.depth, args.height),
        "cylinder": (dia, dia, args.height),
        "tube": (dia, dia, args.height),
        "bracket": (args.width, args.depth, min(args.width, args.depth)),
    }[args.shape]
    off = [abs(got - float(expected)) for got, expected in zip(size, want)]
    ok = max(off) <= 0.05                      # OpenSCAD facets a curve; 0.05 mm is slack enough
    note = "" if ok else (f"asked for {want[0]}x{want[1]}x{want[2]} mm, measured "
                          f"{size[0]}x{size[1]}x{size[2]} mm")

    ctx.memory.outputs.append({"path": str(out), "kind": "model", "verified": ok, "note": note})
    holes = f", {4 if args.hole_diameter else 0} holes of {args.hole_diameter} mm" if args.hole_diameter else ""
    summary = (f"Made {out.name}: a {args.shape} measuring {size[0]}x{size[1]}x{size[2]} mm{holes}, "
               f"with OpenSCAD. Measured from the exported STL.")
    return ToolResult(ok, summary if ok else f"{summary} WARNING: {note}.",
                      {"path": str(out), "shape": args.shape,
                       "measured_mm": list(size), "asked_mm": [float(x) for x in want]},
                      verified=ok, untrusted_text=source)


def register_cad_tools(reg: ToolRegistry) -> None:
    reg.register(ToolSpec(
        "make_part", "Make a dimensioned 3D part (plate, box, cylinder, tube or bracket, with "
                     "optional bolt holes) as an STL with OpenSCAD, measured after export.",
        Capability.DESIGN, RiskLevel.LOCAL_WRITE, PartArgs, make_part, precheck=check_part))
